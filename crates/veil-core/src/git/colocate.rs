//! Colocated Git mode: a real `.git` beside the working copy, kept in step
//! with Veil (feature 9; `docs/design/git-parity/9-colocated-git.md`).
//!
//! The Git bridge's safety rests on two facts: Git only ever sees the
//! public projection, and everything that comes from Git is already public.
//! A `.git` sitting next to cloaked plaintext breaks both, so this module
//! restores them:
//!
//! * **Follow** ([`GitBridge::follow_local`], at the start of every `vl`
//!   command): new commits on local branches are imported. A commit made
//!   here is *local*, not public: it is kept only if its tree is exactly
//!   what Veil would export for its snapshot (and its parents are kept or
//!   public). Otherwise it is **superseded**: Veil exports the snapshot
//!   afresh (the projection), moves the branch (and `HEAD`) from the
//!   original to the replacement by compare-and-swap, records the original
//!   as *held*, and never builds on it or pushes it.
//! * **Mirror** ([`GitBridge::mirror`], at the end of every command):
//!   tags become `refs/heads/*` and release tags `refs/tags/*`, `HEAD`
//!   names `@-`'s export, every write a compare-and-swap against what Git
//!   last held. `.git/index` is `HEAD`'s tree with **skip-worktree** on
//!   every path whose working-copy content may differ from it, or on
//!   every path (**frozen mode**) when `@` is on a cloaked line or under an
//!   unreleased embargo, or `@-` cannot be exported.
//! * **Excludes** ([`write_exclude`]): a generated block in
//!   `info/exclude` holds every protective rule of the effective policy
//!   (`crate::policy_gitignore`), the protected paths on disk, and `*` in
//!   frozen mode.
//! * **Gates**: [`GitBridge::check_push`] (the `pre-push` hook) refuses a
//!   push of a held commit, of one Veil has not imported, or of
//!   `refs/stash`; [`GitBridge::check_staged`] (the `pre-commit` hook)
//!   refuses a commit that stages hidden or protected content.
//!
//! Veil never waits for a Git lock and never removes one: a ref whose lock
//! is taken, or an `index.lock` that exists, means Git is busy, and the
//! write is skipped (the next command catches up). While a Git operation is
//! in progress (rebase, merge, cherry-pick, revert, bisect, `index.lock`)
//! nothing is followed or mirrored except the exclude block.

