//! Round 3 adversarial tests: release artefacts and CI supply chain.
//! `render-formula.sh` is run for real; the workflows are checked
//! statically (GitHub Actions cannot run here).

use std::{
    path::{Path, PathBuf},
    process::Command,
};

const TARGETS: [&str; 4] = [
    "aarch64-apple-darwin",
    "x86_64-apple-darwin",
    "aarch64-unknown-linux-musl",
    "x86_64-unknown-linux-musl",
];

fn workspace() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").canonicalize().unwrap()
}

/// Run `render-formula.sh <tag> <sums>`; (success, stdout, stderr).
fn render(tag: &str) -> (bool, String, String) {
    let sums = tempfile::tempdir().unwrap();
    for t in TARGETS {
        std::fs::write(
            sums.path().join(format!("vl-{t}.tar.xz.sha256")),
            format!("{} *vl-{t}.tar.xz\n", "0".repeat(64)),
        )
        .unwrap();
    }
    let out = Command::new("sh")
        .arg(workspace().join("packaging/homebrew/render-formula.sh"))
        .arg(tag)
        .arg(sums.path())
        .arg("veil-vcs/veil")
        .current_dir(sums.path())
        .output()
        .unwrap();
    (
        out.status.success(),
        String::from_utf8_lossy(&out.stdout).into_owned(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
    )
}

#[test]
fn control_a_plain_release_tag_renders() {
    let (ok, formula, err) = render("v1.2.3");
    assert!(ok, "{err}");
    assert!(formula.contains("version \"1.2.3\""));
    assert!(formula.contains("releases/download/v1.2.3/vl-x86_64-apple-darwin.tar.xz"));
}

// ---- BUG-067: the formula renderer trusts the tag ---------------------------------------

/// The tag check is the shell pattern `[0-9]*.[0-9]*.[0-9]*`, where `*`
/// matches anything, so a tag such as `v1.2.3";system "id";"` is accepted.
/// Git allows `"`, `;` and `|` in tag names. The tag is pasted into Ruby
/// (code in the published formula, run by every `brew install`) and into a
/// `sed` script, where `|` ends the substitution and GNU sed's `e` command
/// runs a shell command on the release runner (which holds a
/// `contents: write` token and the tap token).
#[test]
#[ignore = "BUG-067: render-formula.sh accepts tags with quotes and | (Ruby injection into the formula, sed command execution)"]
fn the_formula_renderer_refuses_hostile_tags() {
    let (ok, formula, _) = render("v1.2.3\";system \"id\";\"");
    assert!(
        !ok,
        "a tag with quotes was accepted; the formula now runs code:\n{}",
        formula.lines().find(|l| l.contains("version")).unwrap_or("")
    );
    let marker = "PWNED-BY-SED-0x41";
    let (ok, _, err) = render(&format!("v1.2.3|g;1e echo {marker} >&2;s|x"));
    assert!(!ok && !err.contains(marker), "sed executed a command from the tag:\n{err}");
}

// ---- BUG-068: CI supply chain ---------------------------------------------------------

fn workflow(name: &str) -> String {
    std::fs::read_to_string(workspace().join(".github/workflows").join(name)).unwrap()
}

/// Every `uses:` reference in the hand-written workflows is a mutable tag
/// (`actions/checkout@v6`, `Swatinem/rust-cache@v2.9.3`, …), not a commit
/// SHA. Whoever controls those tags controls the runner, including
/// `publish-homebrew.yml`, which runs with `contents: write` and the
/// Homebrew tap token. (`release.yml` is generated by dist and has the same
/// pattern; it is listed in the report too.)
#[test]
#[ignore = "BUG-068: workflow actions are referenced by mutable tags, not commit SHAs (incl. the job holding the tap token)"]
fn workflow_actions_are_pinned_by_commit() {
    let mut unpinned = Vec::new();
    for name in ["ci.yml", "nightly.yml", "publish-homebrew.yml", "release.yml"] {
        for line in workflow(name).lines() {
            let Some(r) = line.trim().trim_start_matches("- ").strip_prefix("uses:") else { continue };
            let r = r.trim().trim_matches('"');
            if r.starts_with("./") {
                continue;
            }
            let pinned = r
                .rsplit_once('@')
                .is_some_and(|(_, v)| v.len() == 40 && v.bytes().all(|b| b.is_ascii_hexdigit()));
            if !pinned {
                unpinned.push(format!("{name}: {r}"));
            }
        }
    }
    assert!(unpinned.is_empty(), "unpinned actions:\n{}", unpinned.join("\n"));
}

/// CI pipes the dist installer from a GitHub release straight into `sh`
/// with no checksum, while `actionlint` in the same job is verified.
#[test]
#[ignore = "BUG-068: CI runs curl … cargo-dist-installer.sh | sh without verifying a checksum"]
fn ci_verifies_what_it_downloads_and_runs() {
    let ci = workflow("ci.yml");
    let piped: Vec<&str> = ci.lines().filter(|l| l.contains("curl") && l.contains("| sh")).collect();
    assert!(piped.is_empty(), "unverified download piped to sh:\n{}", piped.join("\n"));
}
